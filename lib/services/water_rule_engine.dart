    final rows = _table[param];
    if (rows == null) return null;
    double? lo, hi;
    for (final r in rows) {
      if (r[2] == "ভালো") {
        final rlo = (r[0] as num).toDouble();
        final rhi = (r[1] as num).toDouble();
        lo = (lo == null || rlo < lo) ? rlo : lo;
        hi = (hi == null || rhi > hi) ? rhi : hi;
      }
    }
    if (lo == null || hi == null) return null;
    return [lo, hi];
  }

