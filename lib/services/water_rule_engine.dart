    final threshold = (avgAbs * 0.05).clamp(0.01, double.infinity); // ৫% পরিবর্তনকে উল্লেখযোগ্য ধরা হচ্ছে

    final level = classify(param, last);
    final isGoodDirectionUp = param == "do" || param == "alkalinity"; // এই প্যারামিটারে বাড়া সাধারণত ভালো (নির্দিষ্ট সীমার মধ্যে)

    String trend;
    if (diff.abs() < threshold) {
      trend = "স্থিতিশীল";
    } else if (diff > 0) {
      trend = "বাড়ছে";
    } else {
      trend = "কমছে";
    }

    String advice;
    if (trend == "স্থিতিশীল") {
      advice = level == "ভালো"
          ? "গত কয়েকটা রিডিংয়ে তেমন পরিবর্তন হয়নি এবং মান স্বাভাবিক পরিসরে আছে — বর্তমান পরিচর্যা চালিয়ে যান।"
          : "মান স্থিতিশীল থাকলেও এখনো স্বাভাবিক পরিসরের বাইরে — আজকের করণীয় পদক্ষেপগুলো অনুসরণ করুন যাতে দ্রুত স্বাভাবিক হয়।";
    } else {
      final directionGood = (trend == "বাড়ছে" && isGoodDirectionUp) || (trend == "কমছে" && !isGoodDirectionUp);
      if (level == "ভালো") {
        advice = "মান $trend, তবে এখনো নিরাপদ পরিসরে আছে — নিয়মিত পর্যবেক্ষণ চালিয়ে যান যাতে সীমার বাইরে না যায়।";
      } else if (directionGood) {
        advice = "ভালো খবর: মান ধীরে ধীরে স্বাভাবিকের দিকে যাচ্ছে ($trend) — বর্তমান ব্যবস্থা কাজ করছে, চালিয়ে যান।";
      } else {
        advice = "সতর্কতা: মান $trend এবং পরিস্থিতি খারাপের দিকে যাচ্ছে — আজই ব্যবস্থা নিন (নিচের করণীয় দেখুন), নাহলে সামনের দিনগুলোতে ঝুঁকি বাড়তে পারে।";
      }
    }

    return {"trend": trend, "advice": advice};
  }

