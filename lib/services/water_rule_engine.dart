  static String classify(String param, double value) {
    final rules = _table[param];
    if (rules == null) return "বিপদ";
    for (final rule in rules) {
      final lo = (rule[0] as num).toDouble();
      final hi = (rule[1] as num).toDouble();
      final level = rule[2] as String;
      if (value >= lo && value <= hi) return level;
    }
    return "বিপদ";
  }

  /// একটা reading-এর সব parameter থেকে সবচেয়ে খারাপ level বের করে overall risk
  static String overallRiskFromReading({
    required double ph,
    required double doLevel,
    required double temp,
    required double ammonia,
    double? turbidity,
    double? nitrite,
    double? nitrate,
    double? alkalinity,
    double? salinity,
  }) {
    const order = ["ভালো", "সতর্ক", "ঝুঁকি", "বিপদ"];
    final levels = <String>[
      classify("ph", ph),
      classify("do", doLevel),
      classify("temp", temp),
      classify("ammonia", ammonia),
      if (turbidity != null) classify("turbidity", turbidity),
      if (nitrite != null) classify("nitrite", nitrite),
      if (nitrate != null) classify("nitrate", nitrate),
      if (alkalinity != null) classify("alkalinity", alkalinity),
      if (salinity != null) classify("salinity", salinity),
    ];

    int worstIdx = 0;
    for (final l in levels) {
      final idx = order.indexOf(l);
      if (idx > worstIdx) worstIdx = idx;
    }
    return order[worstIdx];
  }

